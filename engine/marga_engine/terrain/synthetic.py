"""Explicitly labelled SYNTHETIC terrain for tests and for demos before real data is packaged.

Nothing here is derived from Mars observations. Every grid built here carries
`metadata.synthetic = True`; the route service then adds a warning to every response so the
scientific interface can never show synthetic terrain as if it were NASA data (spec 28.4).
"""
from __future__ import annotations

import math

import numpy as np

from ..geodesy import MARS_RADIUS_M
from .grid import GridGeometry, TerrainGrid, TerrainMetadata

SYNTHETIC_LIMITATION = ("SYNTHETIC: generated analytically for software testing. Not derived from any "
                        "Mars observation; must not be used for scientific or operational interpretation.")


def synthetic_metadata(dataset_id: str, name: str, cell_m: float, notes: str = "") -> TerrainMetadata:
    return TerrainMetadata(
        dataset_id=dataset_id, name=name, site_id=None, mission=None, instrument=None,
        source="generated by marga_engine.terrain.synthetic", crs="geographic lat/lon on Mars 2000 sphere",
        vertical_datum="arbitrary (synthetic)", processing_level="synthetic fixture",
        spatial_resolution_m=cell_m, synthetic=True, status="synthetic-fixture",
        limitations=[SYNTHETIC_LIMITATION] + ([notes] if notes else []))


def geometry_for(ny: int, nx: int, cell_m: float, center_lat: float = -4.6, center_lon: float = 137.4,
                 radius_m: float = MARS_RADIUS_M) -> GridGeometry:
    """Grid whose cells are ~cell_m x cell_m on the ground at center_lat."""
    dlat = math.degrees(cell_m / radius_m)
    dlon = math.degrees(cell_m / (radius_m * math.cos(math.radians(center_lat))))
    return GridGeometry(center_lat + (ny - 1) / 2 * dlat, center_lon - (nx - 1) / 2 * dlon,
                        dlat, dlon, ny, nx, radius_m)


def from_array(elev: np.ndarray, cell_m: float = 20.0, name: str = "synthetic fixture",
               center_lat: float = -4.6, center_lon: float = 137.4) -> TerrainGrid:
    ny, nx = elev.shape
    return TerrainGrid(elev, geometry_for(ny, nx, cell_m, center_lat, center_lon),
                       synthetic_metadata(f"SYNTH-{name.upper().replace(' ', '-')}", name, cell_m))


def ground_xy(geom: GridGeometry) -> tuple[np.ndarray, np.ndarray]:
    """Per-cell (x east, y north) metres from the grid centre - for building analytic surfaces."""
    r = np.arange(geom.nrows)
    c = np.arange(geom.ncols)
    lat = geom.row_lat(r)
    y = (lat - lat.mean()) * math.pi / 180 * geom.radius_m
    x0 = (c - (geom.ncols - 1) / 2) * math.radians(geom.dlon_deg) * geom.radius_m
    X = x0[None, :] * np.cos(np.radians(lat))[:, None]
    Y = np.repeat(y[:, None], geom.ncols, axis=1)
    return X, Y


def flat(ny: int = 41, nx: int = 41, cell_m: float = 20.0, z: float = -4500.0) -> TerrainGrid:
    return from_array(np.full((ny, nx), z, dtype=np.float32), cell_m, "flat plain")


def tilted_plane(ny: int, nx: int, cell_m: float, slope_deg: float, azimuth_deg: float = 0.0) -> TerrainGrid:
    """Planar surface rising toward `azimuth_deg` (clockwise from north) at `slope_deg`."""
    g = geometry_for(ny, nx, cell_m)
    X, Y = ground_xy(g)
    t = math.tan(math.radians(slope_deg))
    az = math.radians(azimuth_deg)
    z = -4500.0 + t * (X * math.sin(az) + Y * math.cos(az))
    return TerrainGrid(z.astype(np.float32), g, synthetic_metadata("SYNTH-PLANE", f"plane {slope_deg} deg", cell_m))


def _tps_fit(x: np.ndarray, y: np.ndarray, v: np.ndarray):
    """Thin-plate spline through (x, y, v): smooth, exact at the anchors, affine far away."""
    n = x.size
    r = np.hypot(x[:, None] - x[None, :], y[:, None] - y[None, :])
    with np.errstate(divide="ignore", invalid="ignore"):
        K = np.where(r > 0, r * r * np.log(r), 0.0)
    P = np.column_stack([np.ones(n), x, y])
    A = np.zeros((n + 3, n + 3))
    A[:n, :n], A[:n, n:], A[n:, :n] = K, P, P.T
    sol = np.linalg.solve(A, np.concatenate([v, np.zeros(3)]))
    w, a = sol[:n], sol[n:]

    def ev(X: np.ndarray, Y: np.ndarray) -> np.ndarray:
        out = a[0] + a[1] * X + a[2] * Y
        for xi, yi, wi in zip(x, y, w):
            rr = np.hypot(X - xi, Y - yi)
            with np.errstate(divide="ignore", invalid="ignore"):
                out = out + wi * np.where(rr > 0, rr * rr * np.log(rr), 0.0)
        return out
    return ev


def gale_demo(cell_m: float = 50.0, anchors: list[tuple[float, float, float]] | None = None,
              anchor_source: str | None = None) -> TerrainGrid:
    """A synthetic stand-in over the MARGA Gale demonstration bounding box
    (lat -4.85..-4.45, lon 137.20..137.60, from frontend mockData GALE_CRATER_METADATA).

    Hand-built features exercise the router: a steep ridge with one breach, mesa-like buttes, a
    scarp in the north-east with one graded ramp, gentle undulation and two no-data gaps. With `anchors`
    [(lat, lon, elevation_m), ...] the surface is bent (thin-plate spline) so it passes exactly
    through those elevations - e.g. the elevation_m values of the repo's science targets - so a
    route profile between two targets agrees with the catalogue. Without anchors the floor simply
    rises to the south. It is NOT a model of real Gale topography either way.
    """
    min_lat, max_lat, min_lon, max_lon = -4.85, -4.45, 137.20, 137.60
    R = MARS_RADIUS_M
    lat_c = (min_lat + max_lat) / 2
    dlat = math.degrees(cell_m / R)
    dlon = math.degrees(cell_m / (R * math.cos(math.radians(lat_c))))
    ny = int(round((max_lat - min_lat) / dlat)) + 1
    nx = int(round((max_lon - min_lon) / dlon)) + 1
    g = GridGeometry(max_lat, min_lon, dlat, dlon, ny, nx, R)
    km_lat = math.pi / 180 * R / 1000
    km_lon = km_lat * math.cos(math.radians(lat_c))

    def features(lat, lon):
        south_km = (-4.58 - lat) * km_lat
        east_km = (lon - 137.40) * km_lon
        z = 12.0 * np.sin(east_km / 3.1) * np.cos(south_km / 2.3)
        ridge_y = (-4.675 - lat) * km_lat * 1000                # E-W ridge, steep north face, one breach
        ridge = 60.0 / (1.0 + np.exp(-ridge_y / 25.0))
        breach = np.exp(-(((lon - 137.392) * km_lon * 1000) / 180.0) ** 2)
        z = z + ridge * (1.0 - 0.95 * breach)
        for blat, blon, rad_m, h in ((-4.663, 137.405, 350, 80), (-4.700, 137.420, 260, 60),
                                     (-4.640, 137.330, 300, 70)):
            d = np.hypot((lat - blat) * km_lat * 1000, (lon - blon) * km_lon * 1000)
            z = z + h * 0.5 * (1.0 - np.tanh((d - rad_m) / 30.0))
        ne = (lat - (-4.53)) * km_lat * 1000 + (lon - 137.50) * km_lon * 1000 * 0.4
        along = (lon - 137.49) * km_lon * 1000                    # graded ramp up the scarp near 137.49 E
        width = 120.0 + 210.0 * np.exp(-(along / 700.0) ** 2)     # ~40 deg wall, ~18 deg on the ramp
        z = z + 400.0 / (1.0 + np.exp(-ne / width))
        rng = np.random.default_rng(1453)                        # deterministic micro-relief
        for _ in range(6):
            wl = rng.uniform(0.3, 1.2)
            ang = rng.uniform(0, math.pi)
            ph = rng.uniform(0, 2 * math.pi)
            z = z + 3.0 * np.sin((east_km * math.cos(ang) + south_km * math.sin(ang)) * 2 * math.pi / wl + ph)
        return z

    lat = g.row_lat(np.arange(ny))[:, None]
    lon = (min_lon + np.arange(nx) * dlon)[None, :]
    F = features(lat, lon)
    if anchors:
        a = np.asarray(anchors, dtype=np.float64)
        ax, ay = (a[:, 1] - 137.40) * km_lon, (a[:, 0] - (-4.58)) * km_lat
        resid = a[:, 2] - features(a[:, 0], a[:, 1])
        base = _tps_fit(ax, ay, resid)((lon - 137.40) * km_lon, (lat - (-4.58)) * km_lat)
    else:
        base = -4500.0 + 70.0 * np.logaddexp(0.0, (-4.58 - lat) * km_lat)
    z = (base + F).astype(np.float32)
    for hlat, hlon, rad_m in ((-4.620, 137.300, 350), (-4.760, 137.450, 250)):
        d = np.hypot((lat - hlat) * km_lat * 1000, (lon - hlon) * km_lon * 1000)
        z[np.broadcast_to(d < rad_m, z.shape)] = np.nan
    notes = ("Covers the MARGA Gale demonstration bounding box only so the UI can be exercised end to end "
             "before a real DEM package (e.g. Mars Trek Gale_DEM_SMG_1m export) is built.")
    if anchors:
        notes += (f" The surface is constrained to pass through the elevation_m of {len(anchors)} catalogue targets"
                  + (f" ({anchor_source})" if anchor_source else "") + "; all other relief is invented.")
    md = synthetic_metadata("SYNTH-GALE-DEMO-001", "Synthetic Gale-box demo terrain", cell_m, notes)
    md.site_id = "GALE"
    return TerrainGrid(z, g, md)
